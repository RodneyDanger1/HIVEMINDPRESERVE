//! Provider usage counters.
//!
//! Budget invariant V1-V6 (blueprint §2a): an absent provider usage value stays
//! absent — it is never stored as `0`. A run with `None` counters is
//! `INCOMPLETE` and its cost must not be settled. Field names follow the values
//! documented in `FACT-REGISTER.md` F1.

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// Token/cache counters reported by the provider for one call or one run.
///
/// All fields are optional because the provider may omit any of them; `None`
/// means "not reported", not zero.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Usage {
    /// Prompt tokens billed for the request.
    #[serde(default)]
    pub prompt_tokens: Option<u64>,
    /// Completion tokens generated by the model.
    #[serde(default)]
    pub completion_tokens: Option<u64>,
    /// Total tokens reported by the provider.
    #[serde(default)]
    pub total_tokens: Option<u64>,
    /// Prompt tokens served from the provider cache.
    #[serde(default)]
    pub prompt_cache_hit_tokens: Option<u64>,
    /// Prompt tokens not served from the provider cache.
    #[serde(default)]
    pub prompt_cache_miss_tokens: Option<u64>,
    /// Reasoning tokens included in the completion.
    #[serde(default)]
    pub reasoning_tokens: Option<u64>,
}

impl Usage {
    /// True when no counter at all was reported.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.prompt_tokens.is_none()
            && self.completion_tokens.is_none()
            && self.total_tokens.is_none()
            && self.prompt_cache_hit_tokens.is_none()
            && self.prompt_cache_miss_tokens.is_none()
            && self.reasoning_tokens.is_none()
    }

    /// Sums two usage reports, keeping absent values absent unless both sides
    /// carry a value (never fabricating a zero).
    #[must_use]
    pub fn checked_add(&self, other: &Usage) -> Usage {
        fn add(left: Option<u64>, right: Option<u64>) -> Option<u64> {
            match (left, right) {
                (Some(a), Some(b)) => Some(a.saturating_add(b)),
                (Some(a), None) | (None, Some(a)) => Some(a),
                (None, None) => None,
            }
        }
        Usage {
            prompt_tokens: add(self.prompt_tokens, other.prompt_tokens),
            completion_tokens: add(self.completion_tokens, other.completion_tokens),
            total_tokens: add(self.total_tokens, other.total_tokens),
            prompt_cache_hit_tokens: add(self.prompt_cache_hit_tokens, other.prompt_cache_hit_tokens),
            prompt_cache_miss_tokens: add(
                self.prompt_cache_miss_tokens,
                other.prompt_cache_miss_tokens,
            ),
            reasoning_tokens: add(self.reasoning_tokens, other.reasoning_tokens),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn absent_stays_absent() {
        let usage = Usage::default();
        assert!(usage.is_empty());
        let json = serde_json::to_value(usage).expect("ser");
        assert_eq!(json["prompt_tokens"], serde_json::Value::Null);
    }

    #[test]
    fn addition_never_invents_zero() {
        let left = Usage {
            prompt_tokens: Some(5),
            completion_tokens: None,
            ..Usage::default()
        };
        let right = Usage {
            prompt_tokens: Some(7),
            completion_tokens: Some(3),
            ..Usage::default()
        };
        let sum = left.checked_add(&right);
        assert_eq!(sum.prompt_tokens, Some(12));
        assert_eq!(sum.completion_tokens, Some(3));
        assert_eq!(sum.total_tokens, None);
    }
}
